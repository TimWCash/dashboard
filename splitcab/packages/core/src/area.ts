// Natural Earth's border is only accurate to about a kilometre, which would put towns like Lifford or Blacklion on
// the wrong side. Places this close to the border are treated as in the Republic: wrongly turning away someone in
// the Republic is worse than now and then pricing a trip from just over the border at NTA fares.
const BORDER_MARGIN_KM = 2;

// Ray casting: a point is inside if a line east from it crosses the edge an odd number of times.
function inside(p: LatLng, polygon: [number, number][]): boolean {
  let hit = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [latI, lngI] = polygon[i]!;
    const [latJ, lngJ] = polygon[j]!;
    if (latI > p.lat !== latJ > p.lat && p.lng < ((lngJ - lngI) * (p.lat - latI)) / (latJ - latI) + lngI) hit = !hit;
  }
  return hit;
}

// Shortest distance from p to the land border, in km, on a local flat projection (fine over a few km).
function kmFromBorder(p: LatLng): number {
  const kx = 111.32 * Math.cos((p.lat * Math.PI) / 180);
  const ky = 110.57;
  let best = Infinity;
  for (let i = 0; i < LAND_BORDER.length - 1; i++) {
    const [aLat, aLng] = LAND_BORDER[i]!;
    const [bLat, bLng] = LAND_BORDER[i + 1]!;
    const ax = (aLng - p.lng) * kx;
    const ay = (aLat - p.lat) * ky;
    const bx = (bLng - p.lng) * kx;
    const by = (bLat - p.lat) * ky;
    const len2 = (bx - ax) ** 2 + (by - ay) ** 2;
    const t = len2 ? Math.max(0, Math.min(1, -(ax * (bx - ax) + ay * (by - ay)) / len2)) : 0;
    best = Math.min(best, Math.hypot(ax + t * (bx - ax), ay + t * (by - ay)));
  }
  return best;
}

export function inServiceArea(p: LatLng): boolean {
  const a = CONFIG.trips.serviceArea;
  const onIsland = p.lat >= a.minLat && p.lat <= a.maxLat && p.lng >= a.minLng && p.lng <= a.maxLng;
  return onIsland && (!inside(p, NORTHERN_IRELAND) || kmFromBorder(p) < BORDER_MARGIN_KM);
}
